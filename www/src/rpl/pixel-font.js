const MISSING = '##### #...# #...# #...# #...# #...# ##### .....';
export const CELL_WIDTH = 6, CELL_HEIGHT = 8;

const _rows = (ch) => (GLYPHS[ch] ?? MISSING).split(' ');

// Text as a graphics object, a row of cells for each line.
export function textGrob(text) {
  const lines = String(text).split('\n').map((line) => [...line]);
  const width = CELL_WIDTH * Math.max(...lines.map((l) => l.length));
  const g = Grob(width, CELL_HEIGHT * lines.length);
  const rowBytes = Math.ceil(width / 8);
  lines.forEach((chars, line) => chars.forEach((ch, k) => _rows(ch).forEach((pixels, r) => {
    for (let c = 0; c < pixels.length; c++) {
      if (pixels[c] !== '#') continue;
      const col = k * CELL_WIDTH + c, row = line * CELL_HEIGHT + r;
      g.bytes[row * rowBytes + (col >> 3)] |= 1 << (col & 7);
    }
  })));
  return g;
}
