import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const version = pkg.version;

function git(args) {
  try {
    return execSync(`git ${args}`, { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
}

const build = git('rev-list --count HEAD') || '0';
const sha = git('rev-parse --short HEAD');
const full = `${version}-build${build}`;

const body = `// Generated by scripts/gen-build-info.mjs; do not edit.
export const VERSION = ${JSON.stringify(version)};
export const BUILD   = ${JSON.stringify(build)};
export const SHA     = ${JSON.stringify(sha)};
export const FULL    = ${JSON.stringify(full)};
`;

writeFileSync(resolve(root, 'www/src/build-info.js'), body);
process.stdout.write(`build-info: ${full}${sha ? ` (${sha})` : ''}\n`);
